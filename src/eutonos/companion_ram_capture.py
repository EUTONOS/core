"""One bounded native RAM write and verified host closeout.

The caller supplies an existing host, actor, fresh attempt, exact allowed paths,
semantic write input, and a new artifact path under .eutonos-local.  Recovery is
reported, never performed automatically.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import sys
import tempfile

from eutonos import ram, tokenslang as ts  # noqa: E402
from eutonos.effects import LocalRoot, decode, digest  # noqa: E402
from eutonos.host import connect, status  # noqa: E402
from eutonos.managed_write import abort as abort_write, begin as begin_write  # noqa: E402

PROFILE = "eutonos.companion-ram-capture.v1"


def canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False)


def now():
    return datetime.now(timezone.utc).isoformat()


def load(path):
    with Path(path).open("r", encoding="utf-8") as stream:
        return json.load(stream)


def write_new(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        descriptor, name = tempfile.mkstemp(prefix=".companion-capture-", suffix=".tmp", dir=path.parent)
        temporary = Path(name)
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as stream:
            json.dump(value, stream, ensure_ascii=False, indent=2)
            stream.write("\n")
            stream.flush()
            os.fsync(stream.fileno())
        os.link(temporary, path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def artifact_paths(root, artifact):
    boundary = (Path(root).resolve() / ".eutonos-local").resolve()
    selected = Path(artifact).resolve()
    ts.require(selected.is_relative_to(boundary) and selected != boundary,
               "denied", "Artifact must be an explicit file under .eutonos-local.")
    return selected, selected.with_name(selected.name + ".result.json")


def freeze_request(value, recorded_at):
    ts.require(isinstance(value, dict), "invalid", "Semantic RAM input must be an object.")
    forbidden = {"operation_id", "at"}.intersection(value)
    experience = value.get("experience")
    ts.require(not forbidden and isinstance(experience, dict) and "recorded_at" not in experience,
               "invalid", "operation_id, at and experience.recorded_at are generated by this tool.")
    request = json.loads(canonical(value))
    request["at"] = recorded_at
    request["experience"]["recorded_at"] = recorded_at
    basis = canonical(request)
    request["operation_id"] = "companion-" + hashlib.sha256(basis.encode("utf-8")).hexdigest()[:24]
    return request


def describe_attempt(coordinator, attempt):
    try:
        item = coordinator.inspect(attempt)
        return {"id": item["id"], "state": item["state"], "generation": item["generation"],
                "reservations": [entry["path"] for entry in item["reservations"]],
                "unfinished_effects": item["unfinished_effects"]}
    except ts.ReadError as exc:
        return {"unavailable": True, "code": exc.code, "message": exc.message}


def recovery(error, coordinator=None, attempt=None, diagnostic=None):
    state = describe_attempt(coordinator, attempt) if coordinator is not None else diagnostic
    action = "Inspect the named attempt and reconcile any unfinished effect before a new explicit operation."
    if isinstance(state, dict) and state.get("state") == "active" and not state.get("unfinished_effects"):
        action = "The attempt is active; inspect its reservations and close out or release only attributed current bytes."
    recommendation = state.get("recommendation") if isinstance(state, dict) else None
    if isinstance(recommendation, dict) and recommendation.get("operation"):
        action = {"operation": recommendation["operation"], "arguments": recommendation.get("arguments", {}),
                  "reason": recommendation.get("reason")}
    return {"profile": PROFILE, "outcome": "error", "code": getattr(error, "code", "unavailable"),
            "message": getattr(error, "message", str(error)), "attempt": state, "recovery": action}


def verify_terminal(root, host, actor, attempt, artifact, result):
    store = ram.Store(LocalRoot(root))
    query = {"profile": ram.READ, "operation": "get", "identity": artifact["request"]["identity"],
             "revision": result["capture"]["revision"], "max_bytes": 32768, "limit": 1}
    try:
        readback = store.read(query)
        item = readback["items"][0]
        diagnostic = status(root, host, actor, attempt)
        attempt_state = diagnostic["attempts"][0]
        current = (readback.get("outcome") == "ok" and readback.get("complete") is True and
                   len(readback.get("items", [])) == 1 and item.get("historical") is False and
                   item.get("identity") == artifact["request"]["identity"] and
                   item.get("path") == result["capture"]["path"] and
                   item.get("record_sha256") == result["capture"]["sha256"] and
                   attempt_state["state"] == "paused" and not attempt_state["reservations"] and
                   not attempt_state["unfinished_effects"])
    except (KeyError, IndexError, OSError, ts.ReadError) as exc:
        return {"profile": PROFILE, "outcome": "historical-prior-completion", "prior": result,
                "current_verified": False, "message": getattr(exc, "message", str(exc))}
    if not current:
        return {"profile": PROFILE, "outcome": "historical-prior-completion", "prior": result,
                "current_verified": False, "readback": {"revision": item.get("record_revision"),
                "historical": item.get("historical")}, "attempt": attempt_state}
    return {**result, "outcome": "already-completed", "current_verified": True,
            "readback": {"path": item["path"], "revision": item["record_revision"],
                         "sha256": item["record_sha256"], "historical": False},
            "host": {"state": "paused", "generation": attempt_state["generation"],
                     "reservations": [], "unfinished_effects": []}}


def verify_plan_readback(root, artifact):
    """Verify the frozen RAM effect and return its exact current record."""
    local = LocalRoot(root)
    request, plan = artifact["request"], artifact["plan"]
    changes = plan["effect"]["changes"]
    ts.require(all(digest(local.read(change["path"])) == digest(decode(change["after"]))
                   for change in changes), "stale", "Frozen RAM effect bytes are not current.")
    record_changes = [entry for entry in changes if entry["path"] == plan["record_path"]]
    ts.require(len(record_changes) == 1, "conflict", "RAM plan has no single intended record write.")
    expected_body = decode(record_changes[0]["after"])
    expected_record = ram.unpack(expected_body)
    expected_revision = expected_record["revision"]
    expected_sha256 = digest(expected_body)
    store = ram.Store(local)
    readback = store.read({"profile": ram.READ, "operation": "get", "identity": request["identity"],
                           "revision": expected_revision, "max_bytes": 32768, "limit": 1})
    ts.require(readback.get("outcome") == "ok" and readback.get("complete") is True and
               len(readback.get("items", [])) == 1, "stale",
               "RAM readback did not return one complete record.")
    item = readback["items"][0]
    ts.require(item.get("path") == plan["record_path"] and item.get("historical") is False and
               item.get("identity") == request["identity"] and item.get("record_revision") == expected_revision and
               item.get("experience", {}).get("revision") == expected_revision and
               item.get("record_sha256") == expected_sha256 and
               digest(local.read(plan["record_path"])) == expected_sha256,
               "stale", "RAM readback differs from the exact latest record.")
    return item


def recover_terminal(root, host, actor, attempt, artifact):
    """Recreate only a missing terminal receipt for an already-closed RAM write."""
    coordinator, authority = connect(root, host, actor)
    state = coordinator.inspect(attempt)
    ts.require(state["actor"] == authority.actor and state["root"] == coordinator._root(authority),
               "wrong-scope", "RAM attempt belongs to another actor or root.")
    ts.require(state["state"] == "paused" and not state["reservations"] and
               not state["unfinished_effects"], "conflict",
               "RAM terminal recovery requires a clean paused attempt.")
    with coordinator._db() as db:
        rows = db.execute("SELECT state,fingerprint,plan FROM effects WHERE attempt=? ORDER BY rowid",
                          (attempt,)).fetchall()
    if not rows:
        return None
    ts.require(len(rows) == 1 and rows[0]["state"] == "completed", "conflict",
               "RAM terminal recovery requires one completed journal effect.")
    journal = ts.loads(rows[0]["plan"])
    plan = artifact["plan"]
    ts.require(rows[0]["fingerprint"] == digest(ts.encoded(plan["effect"])) and
               journal == plan["effect"], "conflict",
               "RAM journal differs from the frozen capture artifact.")
    item = verify_plan_readback(root, artifact)
    return {"profile": PROFILE, "outcome": "completed", "current_verified": True,
            "recovered_terminal": True,
            "capture": {"path": item["path"], "revision": item["record_revision"],
                        "sha256": item["record_sha256"], "writes": len(plan["effect"]["changes"])},
            "readback": {"path": item["path"], "revision": item["record_revision"],
                         "sha256": item["record_sha256"], "historical": False},
            "host": {"state": "paused", "generation": state["generation"],
                     "reservations": [], "unfinished_effects": [], "retired_grants": []}}


def _delivery_terminal(root, host, actor, attempt, artifact, result):
    from . import git_delivery_native as delivery
    result['git_delivery'] = delivery.terminal(root, host, actor, attempt,
        lambda: verify_plan_readback(root, artifact),
        {'completed': 'RAM capture applied and read back.', 'next': 'No automatic follow-up.', 'pending': None})
    return result


def capture(root, host, actor, attempt, semantic, allow_paths, artifact_file, recorded_at=None, *, retry_waiting=False):
    root, host = Path(root).resolve(), Path(host).resolve()
    ts.string(actor); ts.string(attempt)
    allowed = sorted(set(allow_paths))
    ts.require(allowed and len(allowed) == len(allow_paths), "invalid", "Supply unique exact allowed paths.")
    local = LocalRoot(root)
    for path in allowed:
        local.path(path)
    artifact_path, result_path = artifact_paths(root, artifact_file)
    binding = {"root": str(root), "host": str(host), "actor": actor, "attempt": attempt,
               "allowed_paths": allowed, "semantic": semantic}
    binding_id = hashlib.sha256(canonical(binding).encode("utf-8")).hexdigest()
    artifact = None
    if result_path.exists() and not artifact_path.exists():
        raise ts.ReadError("conflict", "Terminal result exists without its frozen capture artifact; preserve both and inspect.")
    waiting_retry = None
    if artifact_path.exists():
        artifact = load(artifact_path)
        ts.require(artifact.get("profile") == PROFILE and artifact.get("binding_id") == binding_id,
                   "conflict", "Existing artifact belongs to different capture input or authority.")
        ts.require(artifact.get("request") == freeze_request(semantic, artifact.get("request", {}).get("at")),
                   "conflict", "Frozen request content differs from the selected semantic input.")
        from . import git_delivery_native as delivery
        try:
            intents = delivery.inspect(root)['native_intents']
            bound = [row for row in intents if row['native']['attempt'] == attempt and row['native']['actor'] == actor]
        except (OSError, ValueError, __import__('sqlite3').Error):
            bound = []
        if bound and not result_path.exists():
            try:
                native_receipt = delivery.recover(root, host, actor, attempt,
                    {'completed': 'RAM capture applied and read back.', 'next': 'No automatic follow-up.', 'pending': None},
                    verify=lambda: verify_plan_readback(root, artifact),
                    effect_id='ram-' + digest(ts.encoded([attempt, artifact['plan']['operation_id'], artifact['plan']['fingerprint']])),
                    fingerprint=artifact['plan']['fingerprint'])
                if native_receipt.get('complete'):
                    try:
                        result = recover_terminal(root, host, actor, attempt, artifact)
                        result['git_delivery'] = native_receipt['git_delivery']
                        write_new(result_path, result)
                        return result
                    except ts.ReadError as exc:
                        return {'profile': PROFILE, 'outcome': 'historical-prior-completion',
                                'current_verified': False, 'native': native_receipt,
                                'git_delivery': native_receipt['git_delivery'], 'message': exc.message}
            except (OSError, ValueError, ts.ReadError) as exc:
                return recovery(exc)
        if result_path.exists():
            return _delivery_terminal(root, host, actor, attempt, artifact,
                                      verify_terminal(root, host, actor, attempt, artifact, load(result_path)))
        try:
            existing = status(root, host, actor, attempt)
            waiting_retry = existing["attempts"][0]
            if (waiting_retry.get("state") == "paused" and not waiting_retry.get("reservations")
                    and not waiting_retry.get("unfinished_effects")):
                result = recover_terminal(root, host, actor, attempt, artifact)
                if result is not None:
                    write_new(result_path, result)
                    return _delivery_terminal(root, host, actor, attempt, artifact, result)
            if not (retry_waiting and waiting_retry.get("state") in {"active", "paused"}
                    and not waiting_retry.get("reservations") and not waiting_retry.get("unfinished_effects")):
                return recovery(ts.ReadError("unknown", "Capture artifact exists for an already-started attempt."),
                                diagnostic=waiting_retry)
        except ts.ReadError as exc:
            if exc.code != "missing":
                return recovery(exc)

    if artifact is None:
        try:
            diagnostic = status(root, host, actor)
            matching = [item for item in diagnostic["attempts"] if item["id"] == attempt]
            if not matching and diagnostic.get("attempts_truncated"):
                try:
                    matching = status(root, host, actor, attempt)["attempts"]
                except ts.ReadError as exc:
                    if exc.code != "missing":
                        raise
            if matching:
                return recovery(ts.ReadError("conflict", "Named attempt already exists; a fresh attempt is required."),
                                diagnostic=matching[0])
        except ts.ReadError as exc:
            return recovery(exc)

    try:
        store = ram.Store(local)
        if artifact is None:
            request = freeze_request(semantic, recorded_at or now())
            plan = store.plan(request, actor)
        else:
            request, plan = artifact["request"], artifact["plan"]
            current_plan = store.plan(request, actor)
            ts.require(current_plan == plan, "stale", "Frozen RAM plan no longer matches current source.")
        planned_paths = sorted(item["path"] for item in plan["effect"]["changes"])
        ts.require(planned_paths == allowed, "denied", "RAM plan paths differ from explicit allowed paths.")
        if artifact is None:
            artifact = {"profile": PROFILE, "binding_id": binding_id, "root": str(root), "host": str(host),
                        "actor": actor, "attempt": attempt, "allowed_paths": allowed,
                        "request": request, "plan": plan}
            write_new(artifact_path, artifact)
        from . import git_delivery_native as delivery
        native_effect_id = 'ram-' + digest(ts.encoded([attempt, plan['operation_id'], plan['fingerprint']]))
        try:
            code_controls = delivery.code_before(root,host,actor,attempt,native_effect_id,plan['effect'])
        except (delivery.DeliveryError, OSError, ValueError, __import__('sqlite3').Error, ts.ReadError):
            # Optional publisher failure cannot prevent the native RAM save.
            # Aggregate release later reports the missing original code proof.
            code_controls = []
        control = delivery.before(root, host, actor, attempt,
                                  'ram-' + digest(ts.encoded([attempt, plan['operation_id'], plan['fingerprint']])), plan['effect'],
                                  session=request['identity']['session_id'], work_id=request['identity']['work_id'])
        coordinator, authority, generation = begin_write(root, host, actor, attempt, allowed)
        changed_paths = [item["path"] for item in plan["effect"]["changes"]]
        coordinator.reserve(authority, attempt, generation, changed_paths)
        applied = ram.apply(coordinator, authority, attempt, generation, plan, plan["fingerprint"])
        item = verify_plan_readback(root, artifact)
        proof = {'outcome': 'typed-verified', 'complete': False,
            'writes': applied['writes'], 'readback': 'verified', 'paths': sorted(changed_paths),
            'actor': actor, 'attempt': attempt, 'generation': generation}
        for code_control in code_controls:
            delivery.verified(code_control,host,proof)
        delivery.verified(control,host,proof)
        expected = {path: digest(local.read(path)) for path in changed_paths}
        closed = coordinator.closeout(authority, attempt, generation, expected,
                                      {"completed": "RAM capture applied and read back.",
                                       "next": "No automatic follow-up.", "pending": None})
        final_state = coordinator.inspect(attempt)
        ts.require(closed["outcome"] == "closed" and final_state["state"] == "paused" and
                   not final_state["reservations"] and not final_state["unfinished_effects"],
                   "conflict", "Host closeout did not reach paused zero-held state.")
        result = {"profile": PROFILE, "outcome": "completed", "current_verified": True,
                  "capture": {"path": item["path"], "revision": item["record_revision"],
                              "sha256": item["record_sha256"], "writes": applied["writes"]},
                  "readback": {"path": item["path"], "revision": item["record_revision"],
                               "sha256": item["record_sha256"], "historical": False},
                  "host": {"state": "paused", "generation": final_state["generation"],
                           "reservations": [], "unfinished_effects": [], "retired_grants": closed["retired_grants"]}}
        result['git_delivery'] = delivery.finish(control, host, lambda: verify_plan_readback(root, artifact),
            {'completed': 'RAM capture applied and read back.', 'next': 'No automatic follow-up.', 'pending': None})
        write_new(result_path, result)
        return result
    except (OSError, RuntimeError, ValueError, ts.ReadError) as exc:
        if locals().get("coordinator") is not None:
            abort_write(root, host, actor, attempt, coordinator, locals().get("authority"))
        return recovery(exc, locals().get("coordinator"), attempt)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", required=True)
    parser.add_argument("--host", required=True)
    parser.add_argument("--actor", required=True)
    parser.add_argument("--attempt", required=True)
    parser.add_argument("--input", required=True, help="Semantic RAM write JSON without generated timestamps or operation ID")
    parser.add_argument("--allow-path", action="append", required=True)
    parser.add_argument("--artifact", required=True, help="New or matching JSON artifact below ROOT/.eutonos-local")
    args = parser.parse_args(argv)
    try:
        result = capture(args.root, args.host, args.actor, args.attempt, load(args.input),
                         args.allow_path, args.artifact)
    except (OSError, RuntimeError, ValueError, ts.ReadError) as exc:
        result = recovery(exc)
    print(json.dumps(result, ensure_ascii=False, sort_keys=True))
    return 0 if result["outcome"] in {"completed", "already-completed"} else 2


if __name__ == "__main__":
    raise SystemExit(main())
