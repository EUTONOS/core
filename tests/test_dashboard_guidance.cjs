const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('src/eutonos/dashboard_static/app.js','utf8');
const ctx=vm.createContext({});
vm.runInContext(source.slice(source.indexOf('function deliveryReadinessItems'),source.indexOf('function deliveryReadiness(')),ctx);
vm.runInContext(source.slice(source.indexOf('function checkpointStats'),source.indexOf('function sinceCheckpoint(')),ctx);
const readiness=vm.runInContext('deliveryReadinessItems',ctx),checkpoint=vm.runInContext('checkpointStats',ctx);
let rows=readiness({modules:{delivery:{authority:{commit:{pending:true,deliverable:false,reasons:['Unknown owner']},publish:{pending:null,deliverable:null,reasons:['No upstream']}},repository:{branch:'topic',divergence:{known:false}},totals:{paths:3}}}});
assert.deepEqual(Array.from(rows,x=>x.label),['Save','Integrate','Publish','Accept']);
assert.equal(rows[0].state,'Needs attention');
assert.equal(rows[1].state,'Unproven');
assert.equal(rows[3].state,'Not recorded');
const stats=checkpoint([{versions:[{recorded_at:'2026-09-15T10:00:00Z',summary:'Saved boundary'}]}],[{start:'2026-09-15T09:00:00Z',model:'old',state:'completed',usage:{input_tokens:2,output_tokens:1}},{start:'2026-09-15T11:00:00Z',model:'new',state:'completed',usage:{input_tokens:10,output_tokens:4}},{start:'2026-09-15T12:00:00Z',model:'new',state:'running'}]);
assert.equal(stats.turns,2);
assert.equal(stats.models,1);
assert.equal(stats.known,1);
assert.equal(stats.input+stats.output,14);
assert.equal(stats.running,1);
assert.equal(checkpoint([],[]),null);
console.log('Dashboard guidance: honest delivery states and since-checkpoint boundaries passed.');
